# Главы: 2.5
#
# Сервис аренды самокатов считает стоимость поездки так. С подпиской первые 30 минут бесплатны,
# каждая следующая минута стоит 5 руб. Без подписки старт стоит 50 руб. и каждая минута — 8 руб.
# Вводятся ответ про подписку («да» или «нет») и длительность поездки в минутах. Выведите
# «К оплате: N руб.», а если с подпиской платить не нужно — «Поездка входит в подписку».
#
# Решение
subscription = input("Подписка есть (да/нет): ")
trip_duration = int(input("Длительность поездки, мин: "))

if trip_duration <= 30 and subscription == "да":
    print("Поездка входит в подписку")
elif trip_duration > 30 and subscription == "да":
    pay = (trip_duration - 30) * 5
    print(f"К оплате: {pay} руб.")
else:
    pay = trip_duration * 8 + 50
    print(f"К оплате: {pay} руб.")


