# Авиакомпания пускает сумку в салон, если её длина не больше 55 см, ширина не больше 40 см,
# высота не больше 20 см, а вес не больше 10 кг. Вводятся длина, ширина и высота — целые числа,
# затем вес — дробное число. Выведите «Можно взять в салон» или «Нужно сдать в багаж».
#
# Решение
length = int(input("Длина, см: "))
width = int(input("Ширина, см: "))
height = int(input("Высота, см: "))
weight = float(input("Вес, кг: "))

if length <= 55 and width <= 40 and height <= 20 and weight <= 10:
    print("Можно взять в салон")
else:
    print("Нужно сдать в багаж")