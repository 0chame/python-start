# Телефон показывает заряд батареи в процентах — целое число от 0 до 100. Выведите состояние
# батареи: от 0 до 15 — «Критический заряд», от 16 до 50 — «Низкий заряд», от 51 до 99 —
# «Нормальный заряд», 100 — «Батарея заряжена».
#
# Решение
power = int(input("Заряд, %: "))

if power <=15:
    print("Критический заряд")
elif 16 <= power <= 50:
    print("Низкий заряд")
elif 51 <= power <= 99:
    print("Нормальный заряд")
else:
    print("Батарея заряжена")