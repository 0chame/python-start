# ДЗ 2, задача 8 «Превышение скорости в каршеринге» (★★☆)
# Главы: 2.4
#
# Сервис каршеринга удерживает с клиента штраф за превышение скорости. Превышение — разница между
# фактической и разрешённой скоростью. При превышении до 20 км/ч включительно штрафа нет, от 21 до
# 40 — 750 руб., от 41 до 60 — 1500 руб., от 61 до 80 — 2500 руб., больше 80 — 5000 руб. Вводятся
# разрешённая и фактическая скорость — целые числа. Выведите «Штраф: N руб.»
# 
# Решение
permitted_speed = int(input("Разрешанная скорость, км/ч: "))
actual_speed = int(input("Фактическая скорость, км/ч: "))

difference = actual_speed - permitted_speed

if difference <= 20:
    fine = 0
    print(f"Штраф: {fine} руб.")
elif 21 <= difference <= 40:
    fine = 750
    print(f"Штарф: {fine} руб.")
elif 41 <= difference <= 60:
    fine = 1500
    print(f"Штарф: {fine} руб.")
elif 61 <= difference <= 80:
    fine = 2500
    print(f"Штарф: {fine} руб.")
else:
    fine = 5000
    print(f"Штарф: {fine} руб.")