# ДЗ 2, задача 13 «Отпуск сотрудника» (★★☆)
# Главы: 2.5
#
# В компании отпуск можно взять после 6 месяцев работы. Число доступных дней — это отработанные
# месяцы, умноженные на 28 и разделённые на 12 нацело: дробная часть отбрасывается. Вводятся число
# отработанных месяцев (от 1 до 12) и число дней, которые просит сотрудник. Если месяцев меньше 6,
# выведите «Отпуск пока недоступен». Иначе выведите «Доступно дней: N», а затем
# «Отпуск согласован» или «Не хватает дней: K».
#
# Решение
months_worked = int(input("Отработано месяцев: "))
days_of_vacation = int(input("Дней отпуска: "))

days_available = (months_worked * 28) // 12
not_enough_days = days_of_vacation - days_available

if months_worked < 6:
    print("Отпуск пока не доступен")
elif days_of_vacation == days_available:
    print(f"Доступно дней: {days_available}")
    print("Отпуск согласован")
else:
    print(f"Доступно дней: {days_available}")
    print(f"Не хватает дней: {not_enough_days}")

