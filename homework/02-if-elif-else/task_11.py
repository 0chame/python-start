# ДЗ 2, задача 11 «Запись к врачу» (★☆☆)
# Главы: 2.5
#
# Клиника записывает на бесплатный приём пациентов с полисом ОМС: детей до 18 лет — к педиатру,
# остальных — к терапевту. Без полиса в этой клинике доступен только платный приём. Вводятся
# ответ, есть ли полис («да» или «нет»), и возраст. Выведите «Запись к педиатру»,
# «Запись к терапевту» или «Доступен платный приём».
#
# Решение
polis = input("Полис ОМС есть (да/нет): ")
age = int(input("Возраст: "))

if age < 18 and polis == "да":
    print("Запись к педиатру")
elif age >= 18 and polis == "да":
    print("Запись к терапевту")
else:
    print("Доступен платный приём")
