# ДЗ 2, задача 1 «Температура в холодильнике» (★☆☆)
# Главы: 2.3, 2.4
#
# Продукты в холодильнике хранятся при температуре от 2 до 6 градусов включительно. Вводится
# показание термометра — целое число. Выведите «Температура в норме», если показание попадает в
# этот диапазон, иначе — «Проверьте холодильник».
#
# Решение
temperature = int(input("Температура, °C: "))


if 2 <= temperature <= 6:
    print("Температура в норме")
else:
    print("Проверьте холодильник")