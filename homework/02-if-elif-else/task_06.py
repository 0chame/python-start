# ДЗ 2, задача 6 «Кешбэк по категории» (★☆☆)
# Главы: 2.4
#
# Банк возвращает часть суммы покупки: на АЗС — 5%, в аптеках — 3%, в супермаркетах — 1%, в
# остальных категориях кешбэка нет. Вводятся категория покупки («азс», «аптека», «супермаркет» или
# другое слово) и сумма покупки — дробное число. Выведите кешбэк с двумя знаками после точки в
# виде «Кешбэк: 75.00 руб.»
#
# Решение
category = input("Категория: ")
summa = float(input("Сумма покупки, руб: "))

if category == "азс":
    azs = summa * 5/100
    print(f"Кэшбек: {azs:.2f} руб.")
elif category == "аптека":
    apteca = summa * 3/100
    print(f"Кэшбек: {apteca:.2f} руб.")
elif category == "супермаркет":
    market = summa * 1/100
    print(f"Кэшбек: {market:.2f} руб.")
else:
    kesh = summa * 0
    print(f"Кэшбек: {kesh:.2f} руб.")