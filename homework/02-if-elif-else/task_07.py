# ДЗ 2, задача 7 «Давление в шинах» (★☆☆)
# Главы: 2.4
#
# Производитель автомобиля указал давление в шинах от 2.2 до 2.5 бар включительно. Вводится
# показание манометра — дробное число. Выведите «Подкачайте шины», если давление ниже нормы,
# «Давление в норме», если оно в пределах нормы, и «Снизьте давление», если выше.
#
# Решение
pressure = float(input("Давление, бар: "))

if pressure < 2.2:
    print("Подкачайте шины")
elif 2.2 <= pressure <= 2.5:
    print("Давление в норме")
else:
    print("Снизьте давление")