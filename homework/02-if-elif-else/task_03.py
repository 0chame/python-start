# Главы: 2.3, 2.4
#
# Служба поддержки отвечает в будни с 9:00 до 18:00 и в субботу с 10:00 до 15:00, в воскресенье не
# работает. Вводятся номер дня недели (1 — понедельник, 7 — воскресенье) и час — целое число от 0
# до 23. Час 18 в будни и час 15 в субботу уже нерабочие. Выведите «Оператор на связи» или
# «Оставьте заявку, ответим в рабочее время».
#
# Решение
day = int(input("День недели (1-7): "))
hour = int(input("Час (0-23): "))

if day <= 5 and 9 <= hour < 18 or day == 6 and 10 <= hour <= 15:
    print ("Оператор на связи")
else:
    print("Оставьте заявку, ответим в рабочее время")