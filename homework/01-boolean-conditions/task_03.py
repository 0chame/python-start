# На аттракцион пускают посетителей ростом от 120 см. Кроме роста нужно одно из двух: возраст от
# 10 лет или сопровождение взрослого. Вводятся рост, возраст и ответ про сопровождение («да» или
# «нет»). Выведите, можно ли на аттракцион.
#
# Решение
height = int(input("Введите рост, см.: "))
age = int(input("Введите возраст: "))
adult = input("Со взрослым (да/нет): ")

height_true = height > 120
other = age >= 10 or 'да' == adult

print(f"Рост, см: {height}")
print(f"Возраст: {age}")
print(f"Со взрослым (да/нет): {adult}")
print(f"Можно на аттракцион: {height_true and other}")