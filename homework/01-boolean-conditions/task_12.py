# Программа проверяет остатки на трёх счетах и должна вывести «True», если хотя бы один остаток
# отрицательный. Программа запускается без ошибок, но в первых двух примерах выводит число 500
# вместо «True» и «False». Исправьте условие.
#
# Решение: исправьте программу ниже
a = int(input("Остаток на счёте 1: "))
b = int(input("Остаток на счёте 2: "))
c = int(input("Остаток на счёте 3: "))

ostatok = a < 0 or b < 0 or c < 0

print(ostatok)