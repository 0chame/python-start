# Купон действует, если в чеке ровно один товар дороже 1000 рублей. Вводятся цены двух товаров.
# Выведите, действует ли купон.
#
# Решение
product_1 = int(input("Цена первого товара, руб.: "))
product_2 = int(input("Цена второго товара, руб.: "))

discount = (product_1 > 1000) != (product_2 > 1000)

print(discount)