# Год високосный, если он делится на 4, но не делится на 100. Годы, которые делятся на 400, тоже
# високосные. Вводится год. Выведите, високосный ли он.
#
# Решение
year = int(input("год: "))

vesokos = (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0 )

print(vesokos)