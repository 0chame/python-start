# Музей продаёт льготный билет детям младше 18 лет и посетителям от 65 лет. Вводится возраст.
# Выведите, положен ли льготный билет и нужен ли полный.
#
# Решение
age = int(input("Введите возраст: "))

lgota = age < 18 or age >= 65
full = not lgota

print(f"Льготный билет: {lgota}")
print(f"Полный билет: {full}")