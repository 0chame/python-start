# Вводятся остаток товара на складе, цена товара и сумма, которая есть у покупателя. Товар можно
# купить, если он есть на складе и денег хватает. Выведите ответ.
#
# Решение
product = int(input("Введите остаток товара на складе, шт.: "))
product_price = int(input("Введите стоимтость товара, руб.: "))
money_buyers = int(input("Введите сколько денег у покупателя, руб.: "))

print(product != 0 and money_buyers >= product_price)