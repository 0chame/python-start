# Заказ отправляют, когда он оплачен, товар есть на складе и адрес указан. Вводятся три ответа
# «да» или «нет»: оплачен ли заказ, есть ли товар, указан ли адрес. Выведите, можно ли отправлять.
# Отдельной строкой выведите, нужно ли звонить покупателю: звонят, если заказ оплачен, а адреса
# нет.
#
# Решение
order_paid = input("Заказ оплачен (да/нет): ")
product = input("Товар есть на складе (да/нет): ")
address = input("Адрес указан (да/нет): ")

dostavka = order_paid == "да" and product == "да" and address == "да"
call = order_paid == "да" and address == "нет"

print(f"Можно отправлять: {dostavka}")
print(f"Позвонить покупателю: {call}")