# В магазине три кассы. Про каждую вводится ответ, открыта ли она: «да» или «нет». Выведите, верно
# ли, что открыта ровно одна касса.
#
# Решение
kassa_1 = input("Касса 1 открыта (да/нет): ")
kassa_2 =  input("Касса 2 открыта (да/нет): ")
kassa_3 =  input("Касса 3 открыта (да/нет): ")

open_1 = kassa_1 == 'да'
open_2 = kassa_2 == 'да'
open_3 = kassa_3 == 'да'

print((open_1 + open_2 + open_3) == 1)